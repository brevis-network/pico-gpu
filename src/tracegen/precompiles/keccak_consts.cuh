  /// Extract limb from round constant.
  __device__ inline constexpr uint16_t rc_value_limb(const int round, const int limb)
  {
    return static_cast<uint16_t>(RC[round] >> (limb * BITS_PER_LIMB));
  }

  /// Extract bit from round constant.
  __device__ inline uint8_t rc_value_bit(const int round, const int bit_index) { return RC_BITS[round][bit_index]; }

  /// Keccak trace columns for one round. Mirrors the Rust-side local `KeccakCols`: the p3 layout
  /// without `preimage` (the permutation input is exported from the first step's `a`).
  template <typename T>
  struct KeccakCols {
    T step_flags[NUM_ROUNDS];
    T export_flag;

    T a[5][5][U64_LIMBS];
    T c[5][64];
    T c_prime[5][64];
    T a_prime[5][5][64];
    T a_prime_prime[5][5][U64_LIMBS];
    T a_prime_prime_0_0_bits[64];
    T a_prime_prime_prime_0_0_limbs[U64_LIMBS];
  };

  /// Keccak trace columns with VM context. Mirrors Rust `KeccakMemCols`: the permutation
  /// columns, then chunk / clk / is_real / export_in (`export_in` = 1 on the first step of a real
  /// permutation, the row that exports the input onto the state bus; `export_flag` = 1 on the
  /// final step, which exports the output). The syscall, the address gadgets and the 25 state
  /// memory accesses live in `KeccakControlCols` (one row per permutation, `keccak_control.cuh`).
  template <typename T>
  struct KeccakMemCols {
    KeccakCols<T> keccak;

    T chunk;
    T clk;
    T is_real;
    T export_in;
  };

  constexpr static const uintptr_t NUM_KECCAK_MEM_COLS = 2537;
  static_assert(sizeof(KeccakMemCols<uint32_t>) == NUM_KECCAK_MEM_COLS * sizeof(uint32_t),
    "KeccakMemCols layout drifted from the Rust side (2537 columns)");

  /// One row per permutation event. Mirrors Rust `KeccakControlCols` (`keccak256/control.rs`).
  /// Uses the `pico_gpu::` gadgets, which carry `populate()`.
  template <typename T>
  struct KeccakControlCols {
    T chunk;
    T clk;
    pico_gpu::SyscallAddrGadget<T> state_addr;
    pico_gpu::AddrAddGadget<T> state_addrs[STATE_NUM_WORDS];
    MemoryReadCols<T> state_read[STATE_NUM_WORDS];
    MemoryWriteCols<T> state_write[STATE_NUM_WORDS];
    T is_real;
  };

  constexpr static const uintptr_t NUM_KECCAK_CONTROL_COLS = 534;
  static_assert(sizeof(KeccakControlCols<uint32_t>) == NUM_KECCAK_CONTROL_COLS * sizeof(uint32_t),
    "KeccakControlCols layout drifted from the Rust side (534 columns)");

  /// Keccak permutation event data (u64 upgrade).
  /// Matches Rust FFIKeccakPermuteEvent layout.
  struct KeccakPermuteEvent {
    uint32_t chunk;
    uint32_t clk;
    uint64_t pre_state[STATE_SIZE];
    uint64_t post_state[STATE_SIZE];

    /// U64 MemoryReadRecord: { value: u64, chunk: u32, timestamp: u32, prev_chunk: u32, prev_timestamp: u32 }.
    MemoryReadRecordU64 state_read_records[STATE_NUM_WORDS];
    /// U64 MemoryWriteRecord: { value: u64, chunk: u32, timestamp: u32, prev_value: u64, prev_chunk: u32, prev_timestamp: u32 }.
    MemoryWriteRecordU64 state_write_records[STATE_NUM_WORDS];
    uint32_t state_addr;
  };

